from digitalcredential.internal.safehttp.blocked import blocked, parse_addr


def test_blocked_special_purpose_addresses() -> None:
    refused = [
        "0.1.2.3",
        "10.0.0.5",
        "100.100.100.200",
        "127.0.0.1",
        "169.254.169.254",
        "172.31.255.255",
        "192.0.0.9",
        "192.0.2.1",
        "192.88.99.2",
        "192.168.1.1",
        "198.19.0.1",
        "198.51.100.7",
        "203.0.113.9",
        "240.0.0.1",
        "255.255.255.255",
        "224.0.0.1",
        "::1",
        "::",
        "::ffff:10.0.0.5",
        "::a00:5",
        "64:ff9b::a9fe:a9fe",
        "2002:7f00:1::",
        "64:ff9b:1::1",
        "100::1",
        "100:0:0:1::1",
        "2001::1",
        "2001:1::1",
        "2001:db8::1",
        "3fff::1",
        "5f00::1",
        "fd12::1",
        "fe80::1",
        "fe80::1%eth0",
        "fec0::1",
        "ff02::1",
    ]
    allowed = [
        "8.8.8.8",
        "100.63.255.255",
        "100.128.0.0",
        "172.32.0.0",
        "192.0.1.255",
        "192.31.196.1",
        "192.52.193.1",
        "192.175.48.1",
        "2606:4700:4700::1111",
        "2620:4f:8000::1",
        "2001:200::1",
        "::ffff:8.8.8.8",
        "64:ff9b::808:808",
        "2002:808:808::",
    ]
    for s in refused:
        assert blocked(parse_addr(s)), s
    for s in allowed:
        assert not blocked(parse_addr(s)), s
